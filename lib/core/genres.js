/**
 * dsh-writer-m — 写作类型 / 步骤链 / 每步提示词：**单一数据源**
 *
 * 为什么把提示词写成数据而不是散在代码里：
 * 用户明确要求「每一步还需要辅助 prompt」，而且首版的差异点之一就是
 * **每步的 prompt 可见、可改**。把 prompt 放在一个纯数据模块里，
 * 宿主半区、客户端半区、用户覆盖（prompts.json）三者才能共用同一份真源。
 *
 * 占位符契约（user 模板里可用，未知 key 渲染成空串）：
 *   {{title}}      项目名 / 书名
 *   {{genre}}      类型中文名
 *   {{theme}}      内容方向：题材
 *   {{audience}}   内容方向：受众
 *   {{tone}}       内容方向：调性
 *   {{words}}      单章目标字数
 *   {{channel}}    小说频道（男频/女频，仅作品定位步）
 *   {{type}}       小说类型（历史/玄幻/…，仅作品定位步）
 *   {{totalWords}} 小说总长度（如「800000 字」，仅作品定位步）
 *   {{tags}}       小说标签/爽点（顿号拼接，仅作品定位步）
 *   {{count}}      候选数量（仅作品定位步）
 *   {{volume}}     章节大纲步的目标卷（只针对这一卷写细纲）
 *   {{extra}}      本次运行的额外要求（用户当场填）
 *   {{template}}   套用的结构模版（骨架 + 约束），没套则为空
 *   {{style}}      套用的风格画像（文风规律，按步骤感知），没套则为空
 *   {{vault}}      参考笔记（Obsidian 知识库正文，有界），没选则为空
 *   {{context}}    前序步骤已产出的内容（有界拼接）
 */

