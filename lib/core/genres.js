export const DEAI_DIMENSIONS = [
  { id: 'explain', label: '解释性旁白', hint: '把「他感到恐惧」这类情绪结论，改成可观察的动作、生理反应或环境细节。' },
  { id: 'parallel', label: '排比与堆砌', hint: '连续三个以上同构短句、形容词串烧，删到只留最有力的一个。' },
  { id: 'summary', label: '总结式收尾', hint: '段末或章末的「这一刻他明白了……」式点题，删掉，让事件自己说话。' },
  { id: 'density', label: '形容词副词过密', hint: '「缓缓地」「轻轻地」「深深地」这类副词删掉九成；形容词每段不超过一个。' },
  { id: 'dialogue', label: '对话书面腔', hint: '对话要能读出声音：允许省略、打断、答非所问；不要让人物说完整的主谓宾。' },
  { id: 'uniform', label: '段落长度均匀', hint: '真人写作段落长短交错。全篇段落都在三四行，就是机器味。' },
]

export function deaiChecklistText() {
  return DEAI_DIMENSIONS.map((d, i) => `${i + 1}. 【${d.label}】${d.hint}`).join('\n')
}

