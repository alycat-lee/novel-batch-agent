/** 目标字数要按候选数翻倍的步骤（作品定位一次产出 {{count}} 个候选）。 */
const STEP_TARGET_PER_CANDIDATE = new Set(['novel:positioning'])

/** 取某一步的目标字数；没配就返回 0（0 = 不按篇幅续写，退回「只有截断才续写」）。 */
export function stepTargetChars(genreId, stepId, count = 1) {
  const key = String(genreId ?? '') + ':' + String(stepId ?? '')
  const base = Number(STEP_TARGET_CHARS[key] ?? 0)
  if (!Number.isFinite(base) || base <= 0) return 0
  if (!STEP_TARGET_PER_CANDIDATE.has(key)) return base
  const n = Math.max(1, Math.min(6, Number.isFinite(Number(count)) ? Number(count) : 1))
  return base * n
}
